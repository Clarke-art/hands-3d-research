const fs=require('node:fs');
const path=require('node:path');
const {pathToFileURL}=require('node:url');
const {chromium}=require('<USER_HOME>/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const out=path.resolve(__dirname,'..');
const assert=(x,m)=>{if(!x)throw new Error(m)};
(async()=>{
  const browser=await chromium.launch({headless:true,executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe'});
  try {
    const page=await browser.newPage({viewport:{width:1440,height:1100}});
    const errors=[]; page.on('pageerror',e=>errors.push(e.message));
    await page.goto(pathToFileURL(path.join(out,'THUMB_DISTAL_CAP_BOUNDARY_REVIEW.html')).href,{waitUntil:'load'});
    await page.waitForSelector('#view-DORSAL.active');
    const directions=['DORSAL','PALMAR','RADIAL','ULNAR','SIDE','TIP'];
    for(const name of directions){
      await page.locator(`.view-button[data-view="${name}"]`).click();
      assert(await page.locator('.native-view.active').getAttribute('data-view')===name,'Direction failed '+name);
    }
    for(const k of 'ABCDE'){
      await page.locator('#toggle-'+k).uncheck();
      assert(await page.locator('#view-TIP .candidate-'+k).evaluate(e=>getComputedStyle(e).display)==='none','Candidate off failed '+k);
      await page.locator('#toggle-'+k).check();
    }
    for(const [id,selector] of [['nail','.nail'],['core','.core'],['expansion','.expansion']]){
      await page.locator('#toggle-'+id).uncheck();
      assert(await page.locator('#view-TIP '+selector).evaluate(e=>getComputedStyle(e).display)==='none',id+' off failed');
      await page.locator('#toggle-'+id).check();
      assert(await page.locator('#view-TIP '+selector).evaluate(e=>getComputedStyle(e).display)!=='none',id+' on failed');
    }
    for(const [id,selector] of [['id','.vertex-ids'],['face-id','.face-ids']]){
      await page.locator('#toggle-'+id).check();
      assert(await page.locator('#view-TIP '+selector).evaluate(e=>getComputedStyle(e).display)!=='none',id+' on failed');
      await page.locator('#toggle-'+id).uncheck();
    }
    await page.locator('#toggle-boundary').check();
    assert(await page.locator('#view-TIP .face-fill').first().evaluate(e=>getComputedStyle(e).display)==='none','Boundary-only faces failed');
    assert(await page.locator('#view-TIP .core').evaluate(e=>getComputedStyle(e).display)==='none','Boundary-only vertices failed');
    await page.locator('#toggle-boundary').uncheck();
    const oldBox=await page.locator('#view-TIP').getAttribute('viewBox');
    await page.locator('#toggle-closeup').check();
    assert(await page.locator('#view-TIP').getAttribute('viewBox')!==oldBox,'Tip closeup failed');
    for(const k of 'ABCD')await page.locator('#toggle-'+k).uncheck();
    await page.locator('#toggle-core').uncheck();await page.locator('#toggle-expansion').uncheck();
    await page.locator('#views').screenshot({path:path.join(out,'renders','_REVIEW_UI_TIP_CANDIDATE_E.png')});
    for(const k of 'ABCD')await page.locator('#toggle-'+k).check();
    await page.locator('#toggle-core').check();await page.locator('#toggle-expansion').check();await page.locator('#toggle-closeup').uncheck();
    await page.locator('.view-button[data-view="DORSAL"]').click();
    await page.locator('#views').screenshot({path:path.join(out,'renders','_REVIEW_UI_DORSAL_ALL_CANDIDATES.png')});
    assert(await page.locator('#human-form select').count()===7,'Seven Human questions required');
    for(const name of ['Q1','Q2','Q3','Q4','Q5','Q6','Q7'])assert(await page.locator(`select[name="${name}"]`).inputValue()==='','Human answer must be blank '+name);
    const dialogs=[];page.on('dialog',async d=>{dialogs.push(d.message());await d.accept()});
    await page.locator('#human-form button[type="submit"]').click();
    assert(dialogs.length===1&&dialogs[0].includes('Q1'),'Empty submission validation failed');
    assert(await page.locator('#result').evaluate(e=>e.textContent)==='','No Human response should be generated by verification');
    assert(errors.length===0,'Browser script errors: '+errors.join(';'));
    const result={status:'PASS',browser:'Headless local Chrome through bundled Playwright',six_direction_switches:true,
      five_candidate_switches:true,nail_switch:true,core_expansion_switches:true,vertex_face_id_switches:true,boundary_only_mode:true,tip_closeup:true,
      all_human_answers_remain_blank:true,no_human_approval_record_generated:true,empty_submit_blocked:true,script_errors:errors,
      screenshots:['_REVIEW_UI_TIP_CANDIDATE_E.png','_REVIEW_UI_DORSAL_ALL_CANDIDATES.png']};
    fs.writeFileSync(path.join(out,'UI_VERIFICATION.json'),JSON.stringify(result,null,2));console.log(JSON.stringify(result));
  }finally{await browser.close()}
})().catch(e=>{console.error(e);process.exitCode=1});
